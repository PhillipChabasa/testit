/* Run with TESTIT_PLAYWRIGHT pointing at an installed playwright-core directory. */
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const http = require('node:http');
const {chromium} = require(process.env.TESTIT_PLAYWRIGHT || 'playwright-core');
const root = path.resolve(__dirname,'../legacy');
const artifacts = path.join(__dirname,'artifacts');
let checks=0;
const ok = (condition,label) => {assert.ok(condition,label);console.log('PASS '+label);checks++;};
(async()=>{
  await fs.mkdir(artifacts,{recursive:true});
  const server=http.createServer(async(req,res)=>{
    try {
      const pathname=decodeURIComponent(new URL(req.url,'http://localhost').pathname);
      const file=path.resolve(root,'.'+(pathname==='/'?'/index.html':pathname));
      if(!file.startsWith(root+path.sep)){res.writeHead(403);return res.end();}
      const content=await fs.readFile(file);
      res.setHeader('Content-Type',({'.html':'text/html','.js':'application/javascript','.css':'text/css','.json':'application/json','.png':'image/png'})[path.extname(file)]||'text/plain');res.end(content);
    }catch{res.writeHead(404);res.end();}
  });
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  const base='http://127.0.0.1:'+server.address().port;
  let browser;
  try {
    browser=await chromium.launch({executablePath:process.env.TESTIT_BROWSER||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
    const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
    const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(base+'/?view=qbank');
    await page.locator('#qb-create-form').waitFor();
    ok(await page.locator('#qb-start').isDisabled(),'empty pool prevents starting');
    await page.getByRole('button',{name:'Add sample bank'}).click();
    ok(await page.locator('#qb-available').textContent()==='4','sample bank available without overwriting existing data');
    await page.locator('[data-config="subjects"][value="Medicine"]').check();
    ok(await page.locator('#qb-available').textContent()==='2','subject filter');
    await page.locator('[data-config="systems"][value="Cardiovascular"]').check();
    ok(await page.locator('#qb-available').textContent()==='1','system and subject intersect');
    await page.locator('[data-config="subjects"][value="Medicine"]').uncheck();
    await page.locator('[data-config="systems"][value="Cardiovascular"]').uncheck();
    await page.locator('#qb-count').fill('2');
    await page.screenshot({path:path.join(artifacts,'create-desktop.png'),fullPage:true});
    const bankBefore=await page.evaluate(()=>localStorage.getItem('testit_quiz_phase1_sample'));
    await page.locator('#qb-start').click();
    await page.locator('#qb-stem').waitFor();
    const first=await page.locator('#qb-stem').textContent();
    await page.keyboard.press('1');
    ok(await page.locator('.qb-answer[aria-checked="true"]').count()===1,'keyboard selects an answer');
    ok(await page.getByRole('region',{name:'Answer explanation'}).count()===0,'tutor hides explanation before submit');
    await page.keyboard.press('f');
    ok(await page.locator('[data-action="flag"]').getAttribute('aria-pressed')==='true','keyboard flags question');
    await page.evaluate(()=>{const el=document.getElementById('qb-stem'),r=document.createRange();r.setStart(el.firstChild,0);r.setEnd(el.firstChild,10);const s=getSelection();s.removeAllRanges();s.addRange(r);});
    await page.getByRole('button',{name:'Highlight selection',exact:true}).click();
    ok(await page.locator('#qb-stem mark').count()===1,'highlight selection uses safe text ranges');
    await page.getByRole('button',{name:'Submit answer',exact:true}).click();
    ok(await page.locator('.qb-explanation').count()===1,'tutor shows detailed explanation after submission');
    ok(await page.locator('.qb-answer:not([disabled])').count()===0,'submitted tutor answers locked');
    await page.locator('[data-action="next"]').click();
    await page.locator('[data-action="previous"]').click();
    ok(await page.locator('#qb-stem').textContent()===first,'navigation preserves current question');
    ok(await page.locator('#qb-stem mark').count()===1,'highlights persist across navigation');
    const snapshot=await page.evaluate(()=>{const v=JSON.parse(localStorage.getItem('testit_qbank_v1'));return Object.values(v.attempts)[0];});
    await page.screenshot({path:path.join(artifacts,'tutor-desktop.png'),fullPage:true});
    await page.getByRole('button',{name:'Suspend',exact:true}).click();
    await page.reload();await page.locator('#nav-qbank').click();
    await page.getByRole('button',{name:'Resume',exact:true}).click();
    const resumed=await page.evaluate(()=>Object.values(JSON.parse(localStorage.getItem('testit_qbank_v1')).attempts)[0]);
    ok(JSON.stringify(resumed.items)===JSON.stringify(snapshot.items),'reload/resume preserves question and option order');
    ok(JSON.stringify(resumed.answers)===JSON.stringify(snapshot.answers)&&resumed.flags.length===1,'reload/resume preserves answers and flags');
    await page.getByRole('button',{name:'End test',exact:true}).click();
    await page.locator('#qb-confirm [data-action="confirm-finish"]').click();
    ok((await page.locator('.qb-metrics').textContent()).includes('Omitted'),'completion reports omissions');
    ok(await page.evaluate(()=>localStorage.getItem('testit_quiz_phase1_sample'))===bankBefore,'test does not mutate bank or legacy progress');
    await page.getByRole('button',{name:'Create another test'}).click();
    // Latest Tutor response drives pool filters.
    await page.locator('[data-config="pool"][value="unused"]').check();
    ok(await page.locator('#qb-available').textContent()==='2','unused pool excludes questions in completed attempt');
    await page.locator('[data-config="pool"][value="flagged"]').check();
    ok(await page.locator('#qb-available').textContent()==='1','flagged pool includes attempt flags');
    await page.locator('[data-config="pool"][value="all"]').check();
    await page.locator('[data-config="mode"][value="exam"]').check();
    await page.locator('[data-config="timed"]').check();
    await page.locator('[data-config="minutes"]').fill('1');
    await page.locator('#qb-count').fill('2');await page.locator('#qb-start').click();
    await page.locator('#qb-stem').waitFor();
    await page.locator('[data-action="answer"]').first().click();
    await page.locator('[data-action="answer"]').nth(1).click();
    ok(await page.locator('[data-action="answer"]').nth(1).getAttribute('aria-checked')==='true','exam allows changing answers');
    ok(await page.locator('.qb-explanation').count()===0&&await page.locator('[data-action="submit-answer"]').count()===0,'exam hides explanations and per-question submit');
    await page.locator('[data-action="next"]').click();await page.locator('[data-action="previous"]').click();
    ok(await page.locator('[data-action="answer"]').nth(1).getAttribute('aria-checked')==='true','exam selections survive navigation');
    const initialClock=await page.locator('#qb-clock').textContent();await page.waitForTimeout(1200);
    ok(await page.locator('#qb-clock').textContent()!==initialClock,'timed exam clock counts down');
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(artifacts,'exam-mobile.png'),fullPage:true});
    ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile layout avoids horizontal page overflow');
    await page.evaluate(()=>{const v=JSON.parse(localStorage.getItem('testit_qbank_v1'));const t=Object.values(v.attempts).find(a=>a.status==='active');t.runningSince=Date.now()-61000;localStorage.setItem('testit_qbank_v1',JSON.stringify(v));QBank.reload();});
    await page.waitForTimeout(1200);
    ok(await page.locator('.qb-metrics').count()===1,'timer expiry finalizes exam once');
    const backup=await page.evaluate(()=>backupManager.buildBackup());
    ok(Object.keys(backup.customData.testit_qbank_v1.attempts).length===2,'backup includes both attempts');
    await page.evaluate(b=>backupManager.applyBackup(b),backup);
    ok(await page.evaluate(()=>Object.keys(JSON.parse(localStorage.getItem('testit_qbank_v1')).attempts).length)===2,'backup restore retains attempts');
    await page.evaluate(()=>{showView('revision');});
    ok(await page.locator('#view-revision').isVisible(),'revision still opens');
    const anki=await page.evaluate(()=>buildAnkiText(conceptEntries(),'extra'));
    ok(anki.includes('How is cardiac output calculated?'),'Anki export retains concept cards');
    // Legacy sample and exact reimport compatibility.
    await page.evaluate(()=>loadSample());
    const legacy=await page.evaluate(()=>({slot:state.activeSlot,quiz:state.quiz}));
    await page.locator('#nav-home').click();
    await page.locator('#home-import-details').evaluate(el=>el.open=true);
    await page.locator('#json-input').fill(JSON.stringify(legacy.quiz));
    await page.evaluate(()=>loadQuiz());
    ok(await page.evaluate(()=>state.activeSlot)===legacy.slot,'identical JSON reimport resumes existing slot');
    await page.evaluate(()=>selectAnswer(state.questions[0].id,Object.keys(state.questions[0].options)[0]));
    const order=await page.evaluate(()=>state.allQuestions.map(q=>[q.id,q._keyMap]));
    await page.evaluate(key=>loadFromSlot(key),legacy.slot);
    ok(JSON.stringify(await page.evaluate(()=>state.allQuestions.map(q=>[q.id,q._keyMap])))===JSON.stringify(order),'legacy practice restores saved presentation');
    ok(await page.evaluate(()=>{const id=state.questions[0].id;state.flags.add(id);scheduleAutosave();backupManager.buildBackup();return JSON.parse(localStorage.getItem(state.activeSlot)).flags.includes(id);}), 'backup flushes pending practice autosave to local storage');
    // Storage failure must not prune any quiz, and export must include in-memory work.
    await page.evaluate(()=>{window.originalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k.startsWith('testit_quiz_'))throw new DOMException('Full','QuotaExceededError');return window.originalSetItem.call(this,k,v);};});
    const countBefore=await page.evaluate(()=>getAllSavedSlots().length);
    await page.evaluate(()=>{state.flags.add(state.questions[0].id);saveProgress();});
    ok(await page.evaluate(()=>getAllSavedSlots().length)===countBefore,'quota failure preserves every existing bank');
    ok(await page.evaluate(()=>backupManager.buildBackup().studyProgress[state.activeSlot].flags.length)>0,'backup includes unsaved practice changes');
    await page.evaluate(()=>{Storage.prototype.setItem=window.originalSetItem;});
    // Offline app shell includes new assets.
    await page.evaluate(()=>navigator.serviceWorker.ready);
    await page.reload();await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
    await context.setOffline(true);await page.goto(base+'/?view=qbank');
    await page.locator('#qb-create-form').waitFor();
    ok(await page.locator('#qb-history .qb-attempt').count()===2,'offline reload loads new assets and saved attempts');
    await context.setOffline(false);
    const syncChecks=await page.evaluate(()=>{
      const local=backupManager.buildBackup(),remote=JSON.parse(JSON.stringify(local));
      const id=Object.keys(remote.customData.testit_qbank_v1.attempts)[0],t=remote.customData.testit_qbank_v1.attempts[id];
      t.revision='remote-branch';t.parentRevision='unrelated-parent';t.savedAt=Date.now()+1000;
      const winner=conflictResolver.resolve(local,remote).winner;
      const merged=winner.customData.testit_qbank_v1;
      const before=JSON.stringify(Object.fromEntries(Object.keys(localStorage).map(k=>[k,localStorage.getItem(k)])));
      let rejected=false;try{backupManager.applyBackup({version:1,studyProgress:{},customData:{testit_gtoken:{access_token:'not-a-token'}}});}catch{rejected=true;}
      const after=JSON.stringify(Object.fromEntries(Object.keys(localStorage).map(k=>[k,localStorage.getItem(k)])));
      return {attempts:Object.keys(merged.attempts).length,original:Object.keys(local.customData.testit_qbank_v1.attempts).length,rejected,unchanged:before===after};
    });
    ok(syncChecks.attempts===syncChecks.original+1,'Drive merge preserves divergent attempt revisions as recovery copies');
    ok(syncChecks.rejected&&syncChecks.unchanged,'backup rejects credential/unrelated keys before writes');
    await page.locator('#qb-history [data-action="open"]').first().click();
    await page.getByRole('button',{name:'Review answers',exact:true}).click();
    await page.evaluate(()=>{document.documentElement.dataset.theme='dark';});
    await page.screenshot({path:path.join(artifacts,'review-mobile-dark.png'),fullPage:true});
    await page.evaluate(()=>{window.originalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k==='testit_qbank_v1')throw new DOMException('Full','QuotaExceededError');return window.originalSetItem.call(this,k,v);};});
    const beforeFailure=await page.evaluate(()=>localStorage.getItem('testit_qbank_v1'));
    await page.locator('[data-action="flag"]').click();
    ok(await page.locator('.view.active .qb-save-alert').isVisible(),'test save failure is persistent and visible');
    ok(await page.evaluate(()=>localStorage.getItem('testit_qbank_v1'))===beforeFailure,'test quota failure preserves stored attempts');
    ok(await page.evaluate(()=>Object.keys(backupManager.buildBackup().customData.testit_qbank_v1.attempts).length)===2,'failed test save remains exportable from memory');
    await page.evaluate(()=>{Storage.prototype.setItem=window.originalSetItem;});
    await page.locator('[data-action="retry"]').click();
    ok(!(await page.locator('.view.active .qb-save-alert').isVisible()),'retry recovers test saves');
    ok(errors.length===0,'no uncaught browser errors: '+errors.join('; '));
    console.log(`Completed ${checks} browser workflow checks. Screenshots: tests/artifacts/`);
  }finally{if(browser)await browser.close();await new Promise(r=>server.close(r));}
})().catch(error=>{console.error(error);process.exitCode=1;});
